/*
 * Background service worker (classic script).
 *
 *  - settings defaults on install/update (chrome.storage.local "settings"); the install date for
 *    the popup's occasional support note ("adbrakeInstalledAt", src/shared/supportprompt.js);
 *  - enables / disables the static DNR rulesets "client_ads" (allow rules that let Twitch's own
 *    client-side ad requests through, on whenever the extension is on) and "trackers";
 *  - per-tab stats in chrome.storage.session, lifetime stats in chrome.storage.local, badge.
 * Content scripts are declared statically in manifest.json (build/main-world.js and
 * build/isolated-world.js, generated by tools/build.py) and obey settings.enabled at runtime.
 * Versions before 2026-11-11 registered them dynamically; removeLegacyScripts() unregisters any
 * such leftovers once (this is the only use of the "scripting" permission).
 * No polling. Network requests: only updater.js, which downloads the three public filter lists
 * (https://easylist.to/easylist/easylist.txt, https://easylist.to/easylist/easyprivacy.txt,
 * https://secure.fanboy.co.nz/fanboy-cookiemonster.txt) weekly via chrome.alarms while
 * "Update filter lists automatically" is on, or when "Update now" is pressed on the options page.
 * Nothing is sent: no telemetry, no remote config.
 */
/* global importScripts, chrome */
importScripts('/src/config.js', '/src/shared/settings.js', '/src/shared/logger.js', '/src/shared/stats.js',
  '/src/shared/supportprompt.js');
// General blocking (all sites). The autoconsent library is optional: if it fails to load,
// cookie pop-ups are only hidden, never auto-rejected.
try {
  importScripts('/src/background/autoconsent-shim.js', '/vendor/autoconsent/autoconsent.cjs.js');
} catch (e) {
  console.warn('[TAS] autoconsent library not loaded', e && e.message);
}
importScripts('/src/shared/blocking.js', '/src/shared/userfilters.js', '/src/shared/filterlist.js', '/src/shared/lists.js', '/src/background/general.js',
  '/src/background/updater.js');

(function () {
  'use strict';
  var ns = self.__TAS__;
  var cfg = ns.config;
  var S = ns.settings;
  var Stats = ns.stats;
  var settingsCache = S.defaults();
  var log = ns.createLogger('bg', function () { return !!settingsCache.debug; });

  // Ids used by the dynamic content-script registrations of versions before 2026-11-11.
  var LEGACY_SCRIPT_IDS = ['tas-page-main', 'tas-bridge-isolated'];
  var RULESETS = { clientAds: 'client_ads', trackers: 'trackers' };
  var LIFETIME_KEY = 'lifetimeStats';

  // Serialise everything that does read-modify-write on storage.
  var queue = Promise.resolve();
  function enqueue(fn) {
    var p = queue.then(fn, fn);
    queue = p.catch(function (e) { log.error('task failed', e && e.message ? e.message : e); });
    return p;
  }

  function readSettings() {
    return chrome.storage.local.get(S.STORAGE_KEY).then(function (r) {
      settingsCache = S.normalize(r[S.STORAGE_KEY]);
      return settingsCache;
    });
  }

  /** Unregister dynamic content scripts left behind by older versions (no-op when none). */
  function removeLegacyScripts() {
    if (!chrome.scripting || typeof chrome.scripting.getRegisteredContentScripts !== 'function') return Promise.resolve();
    return chrome.scripting.getRegisteredContentScripts({ ids: LEGACY_SCRIPT_IDS }).then(function (existing) {
      var ids = (existing || []).map(function (s) { return s.id; });
      if (!ids.length) return undefined;
      log.debug('removing legacy dynamic content scripts', ids.join(', '));
      return chrome.scripting.unregisterContentScripts({ ids: ids });
    });
  }

  function syncRulesets(s) {
    var enable = [], disable = [];
    // client_ads holds allow rules only (since 2.0): Twitch's ad requests must not fail on live
    // streams, whatever EasyList says; blockClientAds now acts in the page (no-fill answer, live and VOD).
    (s.enabled ? enable : disable).push(RULESETS.clientAds);
    (s.enabled && s.blockTrackers ? enable : disable).push(RULESETS.trackers);
    return chrome.declarativeNetRequest.updateEnabledRulesets({ enableRulesetIds: enable, disableRulesetIds: disable });
  }

  function apply() {
    return enqueue(function () {
      return readSettings().then(function (s) {
        return syncRulesets(s).then(function () {
          log.debug('applied settings', JSON.stringify(s));
        });
      });
    });
  }

  // ------------------------------------------------------------------ lifecycle
  chrome.runtime.onInstalled.addListener(function (details) {
    enqueue(function () {
      return chrome.storage.local.get(S.STORAGE_KEY).then(function (r) {
        var o = {};
        o[S.STORAGE_KEY] = S.normalize(r[S.STORAGE_KEY]);
        return chrome.storage.local.set(o);
      });
    });
    enqueue(removeLegacyScripts);
    if (details && details.reason === 'install') {
      // Install date for the occasional support note in the popup (src/shared/supportprompt.js).
      var SP = ns.supportPrompt;
      chrome.storage.local.get(SP.INSTALL_KEY).then(function (r) {
        if (r[SP.INSTALL_KEY]) return null;
        var o = {};
        o[SP.INSTALL_KEY] = Date.now();
        return chrome.storage.local.set(o);
      }).catch(function () {});
    }
    apply();
    log.debug('installed/updated:', details && details.reason);
  });

  chrome.runtime.onStartup.addListener(function () { apply(); });

  chrome.storage.onChanged.addListener(function (changes, area) {
    if (area === 'local' && changes[S.STORAGE_KEY]) apply();
  });

  try { chrome.action.setBadgeBackgroundColor({ color: cfg.badgeColor }); } catch (e) { /* ignore */ }

  // ------------------------------------------------------------------ stats
  function tabKey(tabId) { return 'tab:' + tabId; }

  function updateBadge(tabId, tabStats) {
    try {
      chrome.action.setBadgeText({ tabId: tabId, text: Stats.badgeText(tabStats) }).catch(function () {});
    } catch (e) { /* tab gone */ }
  }

  function recordEvent(tabId, name, data) {
    return enqueue(function () {
      var key = tabKey(tabId);
      return Promise.all([chrome.storage.session.get(key), chrome.storage.local.get(LIFETIME_KEY)]).then(function (res) {
        var tab = res[0][key] || {};
        var stats = Stats.applyEvent(tab.stats, name);
        var text = Stats.describeEvent(name, data);
        var next = {
          stats: stats,
          degraded: tab.degraded || name === 'degraded',
          lastEvent: text ? { text: text, at: Date.now() } : (tab.lastEvent || null)
        };
        var o = {};
        o[key] = next;
        var writes = [chrome.storage.session.set(o)];
        if (Stats.isCounted(name)) {
          var l = {};
          l[LIFETIME_KEY] = Stats.applyEvent(res[1][LIFETIME_KEY], name);
          writes.push(chrome.storage.local.set(l));
        }
        updateBadge(tabId, stats);
        return Promise.all(writes);
      });
    });
  }

  function resetTabOnLoad(tabId) {
    // A new page instance: keep counts for the tab, clear the per-page degraded flag.
    return enqueue(function () {
      var key = tabKey(tabId);
      return chrome.storage.session.get(key).then(function (r) {
        var tab = r[key];
        if (!tab || !tab.degraded) return undefined;
        tab.degraded = false;
        var o = {};
        o[key] = tab;
        return chrome.storage.session.set(o);
      });
    });
  }

  function getState(tabId) {
    return enqueue(function () {
      var key = tabKey(tabId);
      return Promise.all([chrome.storage.session.get(key), chrome.storage.local.get(LIFETIME_KEY), readSettings()]).then(function (res) {
        var tab = res[0][key] || {};
        return {
          tab: { stats: Stats.normalize(tab.stats), degraded: !!tab.degraded, lastEvent: tab.lastEvent || null },
          lifetime: Stats.normalize(res[1][LIFETIME_KEY]),
          settings: res[2]
        };
      });
    });
  }

  function resetStats() {
    return enqueue(function () {
      return chrome.storage.session.clear().then(function () {
        var o = {};
        o[LIFETIME_KEY] = Stats.empty();
        return chrome.storage.local.set(o);
      }).then(function () {
        return chrome.tabs.query({}).then(function (tabs) {
          tabs.forEach(function (t) { updateBadge(t.id, Stats.empty()); });
        });
      });
    });
  }

  chrome.runtime.onMessage.addListener(function (msg, sender, sendResponse) {
    if (!msg || typeof msg !== 'object' || sender.id !== chrome.runtime.id) return false;
    var tabId = sender.tab && typeof sender.tab.id === 'number' ? sender.tab.id : null;
    switch (msg.type) {
      case 'tab-hello':
        if (tabId !== null && msg.top) resetTabOnLoad(tabId);
        return false;
      case 'tab-event':
        if (tabId !== null && typeof msg.name === 'string') recordEvent(tabId, msg.name, msg.data);
        return false;
      case 'popup-get-state':
        if (typeof msg.tabId !== 'number') { sendResponse(null); return false; }
        getState(msg.tabId).then(sendResponse, function () { sendResponse(null); });
        return true;
      case 'reset-stats':
        resetStats().then(function () { sendResponse({ ok: true }); }, function () { sendResponse({ ok: false }); });
        return true;
      default:
        return false;
    }
  });

  chrome.tabs.onRemoved.addListener(function (tabId) {
    enqueue(function () { return chrome.storage.session.remove(tabKey(tabId)); });
  });

  // Make sure the rulesets match settings whenever the worker starts (cheap, idempotent).
  apply();
})();
